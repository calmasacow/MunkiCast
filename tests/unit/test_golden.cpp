LTEST_CASE(the_fixture_exists_and_was_not_written_by_this_run) {
    std::error_code ec;
    if (fs::exists(fixture_dir() / "project.json", ec))
        return;

    // Generate it, then fail: a golden file checked by the run that wrote it has proved nothing.
    Project p = golden_project();
    fs::remove_all(fixture_dir(), ec);
    const auto created = create_project(p, fixture_dir());
    CHECK_MSG(created.has_value(), "{}", created.has_value() ? std::string{} : created.error());

    // The lock and journal are runtime state, not part of the fixture.
    fs::remove_all(fixture_dir() / ".munkicast", ec);
    REQUIRE_MSG(false,
                "the golden fixture was missing and has been written to {} -- review it and "
                "commit it, then run again",
                fixture_dir().string());
}

LTEST_CASE(the_committed_project_still_opens) {
    const ScratchDir sd;
    const fs::path dir = sd.copy_of_fixture();
    REQUIRE_MSG(fs::exists(dir / "project.json"), "the fixture was not copied");

    auto opened = open_project(dir);
    REQUIRE_MSG(opened.has_value(), "{}", opened.error());
    CHECK(!opened->read_only);

    const Project& p = opened->project;
    CHECK_EQ(p.schema_version, kSchemaVersion);
    CHECK_EQ(p.name, std::string("Golden Show"));
    CHECK_EQ(p.canvases.size(), std::size_t{2});
    CHECK_EQ(p.scenes.size(), std::size_t{3});
    CHECK_EQ(p.sources.size(), std::size_t{2});
    CHECK_EQ(p.buses.size(), std::size_t{2});
    CHECK_EQ(p.encodes.size(), std::size_t{2});
    CHECK_EQ(p.audio_encodes.size(), std::size_t{2});
    CHECK_EQ(p.outputs.size(), std::size_t{3});
    // Two destinations sharing one audio bitstream, and one carrying none at all.
    CHECK(p.outputs[0].audio_encode == p.outputs[1].audio_encode);
    CHECK(!p.outputs[2].audio_encode.has_value());
    REQUIRE(p.audio_encode(*p.outputs[0].audio_encode) != nullptr);
    CHECK_EQ(p.audio_encode(*p.outputs[0].audio_encode)->bitrate_kbps, 160);
    CHECK_EQ(p.assets.size(), std::size_t{1});

    // The details most likely to be quietly lost by a format change.
    CHECK_EQ(p.canvases[0].fps.num, 60000);
    CHECK_EQ(p.canvases[0].fps.den, 1001);
    CHECK(p.canvases[1].color_space == ColorSpace::Rec2100Pq);
    CHECK(p.canvases[0].emergency_scene.has_value());
    CHECK_EQ(p.assets[0].bytes, 4294967296ULL);
    CHECK_EQ(p.outputs[0].destination.credential_ref, std::string("youtube-main"));
    // One encode, two destinations: the whole point of ADR-0029, asserted rather than implied.
    CHECK(p.outputs[1].encode == p.outputs[2].encode);
    CHECK(p.outputs[0].encode != p.outputs[1].encode);
    REQUIRE(p.encode(p.outputs[1].encode) != nullptr);
    CHECK(p.encode(p.outputs[1].encode)->rescale.has_value());
    CHECK_EQ(p.encode(p.outputs[1].encode)->encoder.bitrate_kbps, 8000);
    CHECK_EQ(p.decks[0].transition_ms, 420);

    // On-air state is never restored: every open starts on the canvas's emergency scene.
    CHECK(p.decks[0].program_scene == p.canvases[0].emergency_scene);
    CHECK(!p.decks[0].preview_scene.has_value());
    const Scene* live = p.scene(fixed_id(0x50));
    REQUIRE(live != nullptr);
    const Node& group = live->roots[0];
    CHECK(group.blend.mode == BlendMode::Multiply);
    CHECK_NEAR(group.blend.opacity, 0.8, 1e-12);
    REQUIRE(group.children() != nullptr);

    const Node& cam = group.children()->at(0);
    CHECK(cam.layout.fit == FitMode::Cover);
    CHECK_NEAR(cam.layout.crop.left, 8.0, 1e-12);
    CHECK_NEAR(cam.transform.scale.x, 0.5, 1e-12);
    CHECK_EQ(cam.effects.size(), std::size_t{1});
    CHECK(std::holds_alternative<std::int64_t>(cam.effects[0].params.at("count")));
    CHECK(std::holds_alternative<double>(cam.effects[0].params.at("width")));
    CHECK(std::holds_alternative<Id>(cam.effects[0].params.at("link")));
    CHECK(std::holds_alternative<Rgba>(cam.effects[0].params.at("colour")));
    CHECK_EQ(p.scene_links.size(), std::size_t{1});
    CHECK(p.scene_links[0].from == fixed_id(0x50));
    CHECK(p.scene_links[0].to == fixed_id(0x56));
    CHECK(p.scene(fixed_id(0x56))->canvas == p.canvases[1].id);

    CHECK_MSG(is_valid(p), "the committed project no longer validates");
}


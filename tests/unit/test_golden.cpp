/// Fixed ids, so the fixture is the same bytes every time it is generated.
Id fixed_id(std::uint8_t tag) {
    std::array<std::uint8_t, 16> bytes{};
    // A plausible timestamp, then the tag repeated: readable in the file and stable forever.
    bytes[0] = 0x01;
    bytes[1] = 0x93;
    bytes[2] = 0x4a;
    bytes[3] = 0x5b;
    bytes[4] = 0x6c;
    bytes[5] = 0x7d;
    for (std::size_t i = 6; i < bytes.size(); ++i)
        bytes[i] = tag;
    return Id::from_bytes(bytes);
}

/// The current format, written by this build and committed. The byte-for-byte fixture.
fs::path fixture_dir() {
    // Beside the test source, not in the build tree: it is an artefact of the repository.
    return fs::path(MUNKICAST_TEST_FIXTURES) / "golden-project-v4";
}

/// The previous format, frozen. **Never regenerated**: its whole value is that it was written by
/// a build that predates the change, so opening it exercises the real migration rather than a
/// reconstruction of what version 1 is believed to have looked like. It still carries a scene
/// with no canvas and nodes with `canvas_overrides`, which is exactly the point.
fs::path fixture_v1_dir() {
    return fs::path(MUNKICAST_TEST_FIXTURES) / "golden-project-v1";
}

/// A project with one of everything the format can hold, so the fixture exercises the whole
/// writer rather than the parts a default project happens to touch.
Project golden_project() {
    Project p;
    p.schema_version = kSchemaVersion;
    p.id = fixed_id(0x01);
    p.name = "Golden Show";
    p.settings.sample_rate = 48000;
    p.settings.render_queue_frames = 3;
    p.settings.extra.emplace("tuning", 0.25);

    Canvas main_canvas;
    main_canvas.id = fixed_id(0x10);
    main_canvas.name = "Main";
    main_canvas.width = 2560;
    main_canvas.height = 1440;
    main_canvas.fps = Fps::ntsc(60);
    main_canvas.color_space = ColorSpace::Rec709;

    Canvas vertical;
    vertical.id = fixed_id(0x11);
    vertical.name = "Vertical";
    vertical.width = 1080;
    vertical.height = 1920;
    vertical.fps = Fps{60, 1};
    vertical.color_space = ColorSpace::Rec2100Pq;

    Bus program;
    program.id = fixed_id(0x20);
    program.name = "Program";
    program.kind = BusKind::Program;

    Bus vod;
    vod.id = fixed_id(0x21);
    vod.name = "VOD";
    vod.kind = BusKind::Vod;
    vod.gain_db = -2.5;
    vod.sends.push_back(Send{program.id, -6.0, true});
    p.buses.push_back(program);
    p.buses.push_back(vod);

    Source clip;
    clip.id = fixed_id(0x30);
    clip.name = "Be Right Back";
    clip.type = "source.media";
    clip.settings.emplace("path", std::string{"assets/brb.webm"});
    clip.settings.emplace("loop", true);
    clip.settings.emplace("tracks", std::int64_t{2});
    clip.settings.emplace("gain", 0.75);
    Effect filter;
    filter.id = fixed_id(0x32);
    filter.type = "filter.color-correction";
    filter.name = "Camera correction";
    filter.enabled = false;
    filter.params.emplace("brightness", 0.125);
    clip.effects.push_back(filter);
    p.sources.push_back(clip);

    Source camera;
    camera.id = fixed_id(0x31);
    camera.name = "Desk Cam";
    camera.type = "source.v4l2";
    camera.settings.emplace("device", std::string{"/dev/video0"});
    camera.settings.emplace("full_range", false);
    p.sources.push_back(camera);

    // The emergency scene: one source, one looping local clip (ADR-0025).
    Scene emergency;
    emergency.id = fixed_id(0x40);
    emergency.name = "Emergency";
    emergency.canvas = main_canvas.id;
    filter.id = fixed_id(0x42);
    emergency.effects.push_back(filter);
    Node card = make_node(NodeKind::Source, "Card");
    card.id = fixed_id(0x41);
    std::get<SourceData>(card.data).source = clip.id;
    emergency.roots.push_back(std::move(card));

    Scene live;
    live.id = fixed_id(0x50);
    live.name = "Live";
    live.canvas = main_canvas.id;

    Node group = make_node(NodeKind::Group, "Overlay");
    group.id = fixed_id(0x51);
    group.blend.mode = BlendMode::Multiply;
    group.blend.opacity = 0.8;

    Node cam_node = make_node(NodeKind::Source, "Camera");
    cam_node.id = fixed_id(0x52);
    cam_node.transform.position = Vec2{120.0, 64.0};
    cam_node.transform.scale = Vec2{0.5, 0.5};
    cam_node.layout.fit = FitMode::Cover;
    cam_node.layout.size = Vec2{640.0, 360.0};
    cam_node.layout.crop = CropRect{8.0, 0.0, 8.0, 0.0};
    std::get<SourceData>(cam_node.data).source = camera.id;
    std::get<SourceData>(cam_node.data).audio.bus = program.id;
    std::get<SourceData>(cam_node.data).audio.gain_db = -3.0;

    Effect stroke;
    stroke.id = fixed_id(0x53);
    stroke.type = "effect.stroke";
    stroke.enabled = true;
    stroke.params.emplace("width", 2.5);
    stroke.params.emplace("count", std::int64_t{3});
    stroke.params.emplace("colour", Rgba::from_srgb8(255, 160, 40));
    stroke.params.emplace("offset", Vec2{1.0, -1.0});
    stroke.params.emplace("link", fixed_id(0x52));
    stroke.params.emplace("note", std::string{"keeps the camera readable on a bright scene"});
    cam_node.effects.push_back(std::move(stroke));

    group.children()->push_back(std::move(cam_node));

    Node adjust = make_node(NodeKind::Adjustment, "Grade");
    adjust.id = fixed_id(0x54);
    group.children()->push_back(std::move(adjust));

    live.roots.push_back(std::move(group));

    Node clone = make_node(NodeKind::Reference, "Clone of Overlay");
    clone.id = fixed_id(0x55);
    std::get<ReferenceData>(clone.data).target = fixed_id(0x51);
    std::get<ReferenceData>(clone.data).mode = ReferenceMode::Live;
    live.roots.push_back(std::move(clone));

    AudioOverride routing;
    routing.gain_db = -4.0;
    routing.mute = false;
    live.audio_overrides.emplace(fixed_id(0x52), routing);

    // The vertical show is its own scene on its own canvas now, not the same scene repositioned
    // (ADR-0027). What ties them together is a cue, below.
    Scene vertical_live;
    vertical_live.id = fixed_id(0x56);
    vertical_live.name = "Live (Vertical)";
    vertical_live.canvas = vertical.id;
    Node vcam = make_node(NodeKind::Source, "Camera");
    vcam.id = fixed_id(0x57);
    vcam.transform.position = Vec2{40.0, 1200.0};
    vcam.transform.scale = Vec2{0.8, 0.8};
    std::get<SourceData>(vcam.data).source = camera.id;
    vertical_live.roots.push_back(std::move(vcam));

    // Only Main has a safety net here. A canvas without one is not a broken document -- it
    // falls back to black and silence -- and leaving Vertical without one keeps the fixture
    // from asserting that sharing a landscape clip across both is fine, which it is not.
    main_canvas.emergency_scene = emergency.id;
    p.canvases.push_back(main_canvas);
    p.canvases.push_back(vertical);
    p.scenes.push_back(std::move(live));
    p.scenes.push_back(std::move(emergency));
    p.scenes.push_back(std::move(vertical_live));

    p.scene_links.push_back(SceneLink{fixed_id(0x90), fixed_id(0x50), fixed_id(0x56)});

    Deck deck;
    deck.id = fixed_id(0x60);
    deck.name = "Main";
    deck.canvas = main_canvas.id;
    deck.program_scene = p.scenes[0].id;
    deck.preview_scene = p.scenes[1].id;
    deck.transition = "transition.fade";
    deck.transition_ms = 420;
    p.decks.push_back(std::move(deck));

    // Two encodes feeding three destinations, which is the shape ADR-0029 exists for and the
    // one the operator described: the canvas goes out at 1440p to YouTube, and a second,
    // rescaled encode is made once and sent to both Twitch and Kick. Named for what they are
    // and never for a destination, or stopping Twitch while "Twitch 1080p" keeps running would
    // read as a bug.
    Encode full;
    full.id = fixed_id(0x7a);
    full.name = "1440p60 12 Mbps";
    full.canvas = main_canvas.id;
    full.encoder.codec = "h264";
    full.encoder.implementation = "nvenc";
    full.encoder.bitrate_kbps = 12000;
    full.encoder.keyframe_interval_ms = 2000;
    full.encoder.preset = "p5";
    full.encoder.rate_control = "cbr";
    full.encoder.extra.emplace("rc-lookahead", std::int64_t{20});
    full.position = Vec2{520.0, 60.0};
    p.encodes.push_back(full);

    Encode downscaled;
    downscaled.id = fixed_id(0x7b);
    downscaled.name = "1080p60 8 Mbps";
    downscaled.canvas = main_canvas.id;
    downscaled.encoder.codec = "h264";
    downscaled.encoder.implementation = "nvenc";
    downscaled.encoder.bitrate_kbps = 8000;
    downscaled.encoder.keyframe_interval_ms = 2000;
    downscaled.encoder.preset = "p4";
    downscaled.encoder.rate_control = "cbr";
    downscaled.rescale = Vec2{1920.0, 1080.0};
    downscaled.position = Vec2{520.0, 210.0};
    p.encodes.push_back(downscaled);

    // Two audio bitstreams, one shared and one not: the program mix every destination takes,
    // and the copyright-safe VOD track only the recording wants. Fan-out on the audio side is
    // the thing schema 4 exists to be able to say.
    AudioEncode program_audio;
    program_audio.id = fixed_id(0x7c);
    program_audio.name = "AAC 160";
    program_audio.bus = program.id;
    program_audio.codec = "aac";
    program_audio.bitrate_kbps = 160;
    program_audio.position = Vec2{520.0, 360.0};
    p.audio_encodes.push_back(program_audio);

    AudioEncode vod_audio;
    vod_audio.id = fixed_id(0x7d);
    vod_audio.name = "Opus 128";
    vod_audio.bus = vod.id;
    vod_audio.codec = "opus";
    vod_audio.bitrate_kbps = 128;
    vod_audio.extra.emplace("application", std::string{"audio"});
    vod_audio.position = Vec2{520.0, 510.0};
    p.audio_encodes.push_back(vod_audio);

    Output youtube;
    youtube.id = fixed_id(0x70);
    youtube.name = "YouTube";
    youtube.encode = full.id;
    youtube.destination.kind = DestinationKind::Rtmps;
    youtube.destination.url = "rtmps://a.rtmps.youtube.com/live2";
    youtube.destination.credential_ref = "youtube-main";
    youtube.enabled = false;
    youtube.audio_encode = program_audio.id;
    youtube.position = Vec2{1000.0, 60.0};
    p.outputs.push_back(std::move(youtube));

    Output twitch;
    twitch.id = fixed_id(0x71);
    twitch.name = "Twitch";
    twitch.encode = downscaled.id;
    twitch.destination.kind = DestinationKind::Rtmps;
    twitch.destination.url = "rtmps://ingest.twitch.tv/app";
    twitch.destination.credential_ref = "twitch-main";
    twitch.audio_encode = program_audio.id;
    twitch.position = Vec2{1000.0, 210.0};
    p.outputs.push_back(std::move(twitch));

    Output kick;
    kick.id = fixed_id(0x72);
    kick.name = "Kick";
    kick.encode = downscaled.id;
    kick.destination.kind = DestinationKind::Rtmps;
    kick.destination.url = "rtmps://fa723fc1b171.global-contribute.live-video.net/app";
    kick.destination.credential_ref = "kick-main";
    // Deliberately no audio encode: a destination may carry none, and validate() warns about
    // it rather than refusing. The fixture has to hold the shape it permits.
    kick.position = Vec2{1000.0, 360.0};
    p.outputs.push_back(std::move(kick));

    Asset asset;
    asset.id = fixed_id(0x80);
    asset.path = "assets/brb.webm";
    asset.sha256 = "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855";
    asset.bytes = 4294967296ULL;
    asset.relocation_hints.push_back("/home/someone/Videos/brb.webm");
    p.assets.push_back(std::move(asset));
    return p;
}

class ScratchDir {
public:
    ScratchDir() {
        path_ = fs::temp_directory_path() / std::format("munkicast-golden-{}", ::getpid());
        std::error_code ec;
        fs::remove_all(path_, ec);
        fs::create_directories(path_, ec);
    }
    ~ScratchDir() {
        std::error_code ec;
        fs::remove_all(path_, ec);
    }
    ScratchDir(const ScratchDir&) = delete;
    ScratchDir& operator=(const ScratchDir&) = delete;

    [[nodiscard]] fs::path copy_of(const fs::path& fixture) const {
        const fs::path to = path_ / "Golden.munkicast";
        std::error_code ec;
        fs::copy(fixture, to, fs::copy_options::recursive, ec);
        return to;
    }
    [[nodiscard]] fs::path copy_of_fixture() const { return copy_of(fixture_dir()); }

private:
    fs::path path_;
};

